// Only newly claimed synthetic volumes; never connects to an existing database.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';

const image = process.argv[2] || process.env.PIXB_DATABASE_IMAGE || 'pixb-postgres:local';
const upstream =
  process.argv[3] ||
  'postgres:18-alpine@sha256:77f585114c32fbca283dc835b0596f4e52b51b4c6662d7810b2f4084f60a1873';
const prefix = `pixb-pg-check-${randomBytes(6).toString('hex')}`;
const volume = `${prefix}-data`;
const container = `${prefix}-db`;
const claim = randomBytes(24).toString('hex');
const password = randomBytes(24).toString('hex');
let claimed = false;
let running = false;

function docker(args, input) {
  const result = spawnSync('docker', args, {
    encoding: 'utf8',
    input,
    maxBuffer: 8 * 1024 ** 2,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(result.stderr || result.stdout);
  return result.stdout.trim();
}
function sql(query, database = 'probe') {
  return docker(
    [
      'exec',
      '-i',
      container,
      'psql',
      '-U',
      'probe',
      '-d',
      database,
      '-At',
      '-v',
      'ON_ERROR_STOP=1',
    ],
    query,
  );
}
async function start(databaseImage) {
  docker([
    'run',
    '-d',
    '--name',
    container,
    '--label',
    `pixb.check.claim=${claim}`,
    '--network',
    'none',
    '--mount',
    `type=volume,src=${volume},dst=/var/lib/postgresql`,
    '-e',
    'POSTGRES_USER=probe',
    '-e',
    'POSTGRES_DB=probe',
    '-e',
    `POSTGRES_PASSWORD=${password}`,
    databaseImage,
  ]);
  running = true;
  for (let i = 0; i < 150; i++) {
    try {
      // initdb's temporary server accepts sockets only; wait for the final TCP server.
      docker(['exec', container, 'pg_isready', '-h', '127.0.0.1', '-U', 'probe', '-d', 'probe']);
      return;
    } catch {
      if (docker(['inspect', '--format', '{{.State.Running}}', container]) !== 'true') break;
      await new Promise((resolve) => setTimeout(resolve, 300));
    }
  }
  throw new Error(`PostgreSQL did not start: ${docker(['logs', container])}`);
}
function stop() {
  docker(['stop', '--time', '30', container]);
  docker(['rm', container]);
  running = false;
}
const snapshotQuery = `
  SELECT json_build_object(
    'rows', (SELECT json_agg(t ORDER BY id)::text FROM
      (SELECT id::text, title, encode(payload, 'hex') AS payload, amount::text,
        happened::text FROM sample) t),
    'children', (SELECT json_agg(t ORDER BY id)::text FROM child t),
    'sequence', (SELECT last_value::text FROM sample_id_seq),
    'collation', (SELECT json_agg(title ORDER BY title COLLATE "fr-x-icu")::text FROM sample),
    'hash', encode(digest('PixB', 'sha256'), 'hex'),
    'unaccent', unaccent('Été à Noël'),
    'xml', xpath('/a/text()', '<a>cozy</a>'::xml)::text,
    'uuid', uuid_generate_v5(uuid_ns_dns(), 'pixb.local')::text
  )::text;
`;

try {
  docker(['volume', 'create', '--label', `pixb.check.claim=${claim}`, volume]);
  assert.equal(
    JSON.parse(docker(['volume', 'inspect', volume]))[0].Labels['pixb.check.claim'],
    claim,
  );
  claimed = true;
  const hashes = (databaseImage) =>
    docker([
      'run',
      '--rm',
      '--read-only',
      '--network',
      'none',
      '--entrypoint',
      'sha256sum',
      databaseImage,
      '/usr/local/bin/postgres',
      '/usr/local/bin/psql',
      '/usr/local/bin/pg_dump',
      '/usr/local/bin/pg_restore',
      '/usr/local/bin/docker-entrypoint.sh',
    ]);
  assert.equal(hashes(image), hashes(upstream));
  console.log('PASS server, clients, backup tools, and entrypoint are byte-identical to upstream');

  await start(upstream);
  const version = sql('SHOW server_version;');
  const extensions = sql('SELECT name FROM pg_available_extensions ORDER BY name;');
  sql(`
    CREATE EXTENSION pgcrypto;
    CREATE EXTENSION "uuid-ossp";
    CREATE EXTENSION unaccent;
    CREATE EXTENSION pg_trgm;
    CREATE EXTENSION citext;
    CREATE TABLE sample (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title text NOT NULL UNIQUE, payload bytea NOT NULL, amount numeric(30,8),
      happened timestamptz NOT NULL
    );
    CREATE TABLE child (id bigint PRIMARY KEY, parent bigint REFERENCES sample ON DELETE CASCADE);
    INSERT INTO sample (id,title,payload,amount,happened) VALUES
      (9007199254740993,'Été français 日本語 🦊',decode('0001feff','hex'),12345678901234567890.12345678,'2026-10-25 01:30:00+02'),
      (9223372036854775806,'cozy',decode('ff00','hex'),-0.00000001,'2026-11-02 12:00:00+01');
    INSERT INTO child VALUES (1,9007199254740993);
    SELECT setval('sample_id_seq', 100);
    CREATE INDEX sample_title_trgm ON sample USING gin(title gin_trgm_ops);
  `);
  const before = sql(snapshotQuery);
  stop();

  await start(image);
  assert.equal(sql('SHOW server_version;'), version);
  assert.equal(sql('SELECT name FROM pg_available_extensions ORDER BY name;'), extensions);
  assert.equal(sql('SHOW jit;'), 'off');
  assert.equal(sql('SELECT pg_jit_available();'), 'f');
  assert.equal(sql(snapshotQuery), before);
  // Even with a session requesting JIT, an absent optional provider must fall back.
  assert.match(
    sql(
      'SET jit=on; SET jit_above_cost=0; SELECT sum(i::bigint*i) FROM generate_series(1,10000) i;',
    ),
    /333383335000$/,
  );
  sql('BEGIN; DELETE FROM sample; ROLLBACK;');
  assert.equal(sql(snapshotQuery), before);
  assert.throws(() => sql('INSERT INTO child VALUES (2,42);'), /foreign key constraint/);
  assert.throws(
    () => sql("INSERT INTO sample (title,payload,happened) VALUES ('cozy','','now');"),
    /unique constraint/,
  );
  sql(
    "INSERT INTO sample(title,payload,happened) VALUES ('written by slim',decode('010203','hex'),'2026-11-02 00:00:00Z');",
  );
  const after = sql(snapshotQuery);
  console.log(
    'PASS same-volume switch preserves data, ICU ordering, extensions, constraints, transactions, and JIT fallback',
  );

  docker([
    'exec',
    container,
    'pg_dump',
    '-U',
    'probe',
    '-d',
    'probe',
    '-Fc',
    '-f',
    '/tmp/probe.dump',
  ]);
  sql('CREATE DATABASE restored;');
  docker([
    'exec',
    container,
    'pg_restore',
    '-U',
    'probe',
    '-d',
    'restored',
    '--single-transaction',
    '--exit-on-error',
    '/tmp/probe.dump',
  ]);
  assert.equal(sql(snapshotQuery, 'restored'), after);
  console.log('PASS custom-format dump and atomic restore preserve synthetic data');
  stop();

  await start(upstream);
  assert.equal(sql(snapshotQuery), after);
  assert.equal(sql(snapshotQuery, 'restored'), after);
  console.log('PASS returning to the exact upstream version preserves writes and restored data');
} finally {
  if (running) {
    const info = JSON.parse(docker(['inspect', container]))[0];
    assert.equal(info.Config.Labels['pixb.check.claim'], claim);
    stop();
  }
  if (claimed) {
    assert.equal(
      JSON.parse(docker(['volume', 'inspect', volume]))[0].Labels['pixb.check.claim'],
      claim,
    );
    docker(['volume', 'rm', volume]);
  }
}
